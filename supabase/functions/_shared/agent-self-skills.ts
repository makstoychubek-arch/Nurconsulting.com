const INTRO: Record<string, string[]> = {
  saule: ['Я по продажам и карточкам.', 'Моя зона — цифры и карточки WB.'],
  amina: ['Я по рекламе / РК.', 'Моя зона — кампании WB.'],
  anton: ['Я по логистике и остаткам.', 'Моя зона — FBS / склады.'],
  alina: ['Я по раздачам и отзывам.', 'Моя зона — выкупы, фото карточки, покупатели.'],
  karina: ['Я координатор смены.', 'Свожу команду и доступы кабинетов.'],
  muha: ['Я по визуалу.', 'Рисую кадры под карточки.'],
};

/** Ответ «что умеешь» от конкретного агента. */
export function selfSkillsReply(agent: string): string {
  const key = agent in SKILLS ? agent : 'karina';
  const intro = pick(INTRO[key] || INTRO.karina);
  const lines = SKILLS[key].map((s) => `• ${s}`);
  const tail = pick([
    'Кабинет кидай в фразе — Baza / SAAI / Zevina / Elium.',
    'Мутации (создать/поменять/пригласить) — только после твоего «да».',
    'Коротко пиши задачу — разберём.',
  ]);
  return [intro, ...lines, '', tail].join('\n');
}

/** Агент из текста: «Алина что умеешь» / иначе null. */
export function selfSkillsNamedAgent(text: string): string | null {
  const t = String(text || '').toLowerCase().replace(/ё/g, 'е');
  if (/саул[еэ]/.test(t)) return 'saule';
  if (/амина/.test(t)) return 'amina';
  if (/антон/.test(t)) return 'anton';
  if (/алина/.test(t)) return 'alina';
  if (/мух[ауеы]/.test(t)) return 'muha';
  if (/карина/.test(t)) return 'karina';
  return null;
}
