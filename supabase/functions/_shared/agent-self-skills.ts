/** Владелец спрашивает про умения / зону ответственности (с допуском опечаток). */
export function wantsSelfSkills(text: string): boolean {
  const t = normalizeBotText(text);
  if (!t || t.length > 140) return false;
  if (/^(помощь|команды|help|skills|чтоумеешь|ктоя|whoami|зона)$/i.test(t)) {
    return true;
  }
  if (fuzzyIncludesAny(t, SKILLS_ASK_PHRASES)) return true;
  // slash-варианты
  if (/^\/(help|skills|чтоумеешь|ктоя|whoami|зона)(@\w+)?$/i.test(String(text || '').trim())) {
    return true;
  }
  return false;
}

