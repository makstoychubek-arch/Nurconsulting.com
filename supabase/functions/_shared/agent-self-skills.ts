import { pick } from './agent-voice.ts';

/** Владелец спрашивает про умения / зону ответственности. */
export function wantsSelfSkills(text: string): boolean {
  const t = String(text || '')
    .replace(/@\w+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е');
  if (!t || t.length > 120) return false;
  return (
    /(что\s+(ты\s+)?умеешь|чем\s+(ты\s+)?занимаешься|твои?\s+(задач|зон|обязанност|навык|функц)|какие\s+у\s+тебя\s+(задач|функц|возможност)|что\s+ты\s+делаешь|твоя\s+зона|скиллы?|skills?|capabilities|что\s+можешь)/i
      .test(t) ||
    /^(помощь|команды|help)$/i.test(t) ||
    /(расскажи|напомни).{0,20}(что\s+умеешь|свои?\s+задач|свою\s+зону)/i.test(t)
  );
}

