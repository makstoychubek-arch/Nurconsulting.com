/** Ответ «что умеешь» от конкретного агента (память зоны). */
export function selfSkillsReply(agent: string): string {
  const key = agent in SKILLS ? agent : 'karina';
  const intro = pick(INTRO[key] || INTRO.karina);
  const lines = SKILLS[key].map((s) => `• ${s}`);
  const tail = pick([
    'Кабинет кидай в фразе — Baza / SAAI / Zevina / Elium.',
    'Мутации (создать/поменять/пригласить) — только после твоего «да».',
    'Коротко пиши задачу — разберём.',
    ...WOW_TAIL,
  ]);
  return [
    intro,
    'Запомнила свою зону — вот что умею:',
    ...lines,
    '',
    tail,
  ].join('\n');
}

/** Агент из текста: «Алина что умеешь» / иначе null (с опечатками имён). */
export function selfSkillsNamedAgent(text: string): string | null {
  const t = normalizeBotText(text);
  if (/саул[еэа]?/.test(t) || fuzzyIncludesAny(t, ['сауле', 'саула'])) return 'saule';
  if (/амин/.test(t)) return 'amina';
  if (/антон/.test(t)) return 'anton';
  if (/алин/.test(t)) return 'alina';
  if (/мух[ауеыи]?/.test(t)) return 'muha';
  if (/карин/.test(t)) return 'karina';
  return null;
}

/** Список скиллов агента (для тестов / памяти). */
export function listAgentSkills(agent: string): string[] {
  const key = agent in SKILLS ? agent : 'karina';
  return [...SKILLS[key]];
}
