export function msgOpenCashback(pct: number, product?: string | null): string {
  const p = (product || '').trim();
  const what = p ? ` (${p})` : '';
  return (
    `Да, актуально 🙌 Это кэшбек ${pct}%${what}.\n` +
    `Высылаю ТЗ для ознакомления — после прочтения напишите «ключ», вышлю ключевой запрос.`
  );
}

export function msgOpenBarter(product?: string | null, deadline?: string | null): string {
  const p = (product || '').trim();
  const what = p ? ` по позиции: ${p}` : '';
  const d = (deadline || '').trim();
  const when = d ? `\nСрок заказа: ${d}` : '';
  return (
    `Да, актуально 🙌 Это бартер${what}.${when}\n` +
    `Высылаю ТЗ для ознакомления — после прочтения напишите «ключ», вышлю ключевой запрос.`
  );
}

