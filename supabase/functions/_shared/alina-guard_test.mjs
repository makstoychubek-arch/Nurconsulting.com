import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import assert from 'node:assert/strict';
const src = readFileSync(new URL('./alina-guard.ts', import.meta.url), 'utf8').replace(/^export /gm, '');
const g = new Function(stripTypeScriptTypes(src) + '\nreturn { wantsHuman, isAngry, unsafeReply, dedupeReplies, startsWithGreeting, stripGreeting, isGreetingOnly, applyGreeting, similarReply, dropRecentSimilar, promisesMore, withReplyContext, recentWindowMs }')();
for (const t of ['Менеджер!', 'позовите менеджера', 'Можно поговорить с менеджером?', 'вы бот?', 'Ты бот или человек', 'соедините с человеком', 'хочу поговорить с живым человеком', 'с кем я говорю', 'у меня жалоба', 'Это автоответчик?']) assert.ok(g.wantsHuman(t), t);
for (const t of ['Пижама 3 в 1 шоколадная', 'Они маломерят?', 'Сейчас оформлю', 'как дела', 'можно фото', 'спасибо']) assert.ok(!g.wantsHuman(t), 'ложное: ' + t);
for (const t of ['Я вас 5 ый раз прошу прислать фото', 'сколько можно', 'это безобразие', 'тупой бот 😡']) assert.ok(g.isAngry(t), t);
assert.ok(!g.isAngry('Спасибо большое'));
assert.ok(g.unsafeReply('Я бот и не могу'));
assert.ok(g.unsafeReply('Артикул 1939871819'));
assert.ok(g.unsafeReply('https://basket-53.wbbasket.ru/vol1/1.webp'));
assert.ok(!g.unsafeReply('Ближайшее место завтра, 25 ноября'));
assert.deepEqual(g.dedupeReplies(['Секунду, уточню.'], ['Секунду, уточню.']).length, 1);
assert.notEqual(g.dedupeReplies(['Секунду, уточню.'], ['секунду уточню'])[0], 'Секунду, уточню.');
assert.deepEqual(g.dedupeReplies(['Фото пришлю позже'], ['Фото пришлю позже!']), []);
assert.deepEqual(g.dedupeReplies(['Привет!'], []), ['Привет!']);
assert.ok(g.startsWithGreeting('Здравствуйте!')); assert.ok(g.startsWithGreeting('Добрый вечер, как вам?')); assert.ok(!g.startsWithGreeting('Пижама есть'));
assert.equal(g.stripGreeting('Здравствуйте! Какую модель смотрите?'), 'Какую модель смотрите?');
assert.equal(g.stripGreeting('Привет!'), '');
assert.ok(g.isGreetingOnly('Здравствуйте)')); assert.ok(g.isGreetingOnly('Добрый день!')); assert.ok(!g.isGreetingOnly('Здравствуйте, какую модель хотите?'));
assert.deepEqual(g.applyGreeting(['Привет! Какую модель?'], true), ['Какую модель?']);
assert.deepEqual(g.applyGreeting(['Привет!'], true), []);
assert.deepEqual(g.applyGreeting(['Какую модель?'], false), ['Здравствуйте! Какую модель?']);
assert.deepEqual(g.applyGreeting(['Привет! Какую?'], false), ['Привет! Какую?']);
const a = 'Здравствуйте! Уточните модель 🙌\n• Пижама 2в1 шоколадный\n• Пижама 3в1 молочный', b = 'Какую модель выбрать? 🙌\n• Пижама 2в1 шоколадный\n• Пижама 3в1 молочный';
assert.ok(g.similarReply(a, b), 'тот же список моделей');
assert.ok(!g.similarReply('Ближайшее место завтра, 25 ноября', 'Заказ вижу, какой размер заказали?'));
assert.ok(g.similarReply('Фото пришлю чуть позже, передала менеджеру', 'Передала менеджеру, фото пришлю чуть позже'));
assert.deepEqual(g.dropRecentSimilar([b, 'Спасибо, ссылку получила!'], [a]), ['Спасибо, ссылку получила!']);
for (const t of ['Минуту сейчас пришлю', 'щас скину', 'подождите пожалуйста', 'сейчас оформлю']) assert.ok(g.promisesMore(t), t);
for (const t of ['Пижама 3в1 шоколадная', 'какой размер', 'спасибо']) assert.ok(!g.promisesMore(t), 'ложное: ' + t);
for (const t of ['Молочный 🥰', 'Не дошло, поэтому спрашиваю 😇', 'Хорошо 🙏', 'спасибо ❤️', '😂😂']) { assert.ok(!g.isAngry(t), 'смайл не злость: ' + t); assert.ok(!g.wantsHuman(t), 'смайл не просьба: ' + t); }
assert.ok(g.isAngry('😡')); assert.ok(g.isAngry('это 🤬'));
assert.equal(g.withReplyContext('Эта', 'Пижама 3в1 молочный'), 'Эта (в ответ на «Пижама 3в1 молочный»)');
assert.equal(g.withReplyContext('Давайте 3в1 шоколадную', 'Пижама 3в1 молочный'), 'Давайте 3в1 шоколадную');
assert.equal(g.withReplyContext('Эта', ''), 'Эта');
assert.equal(g.recentWindowMs('Выберите:\n• Пижама 2в1'), 300000); assert.equal(g.recentWindowMs('Спасибо'), 90000);
console.log('PASS: alina-guard');
